package com.clussmanproductions.trafficcontrol.blocks;

import com.mojang.serialization.MapCodec;
import net.minecraft.core.Direction;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.HorizontalDirectionalBlock;
import net.minecraft.world.level.block.Mirror;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;

public class BlockTrafficLightControlBox extends HorizontalDirectionalBlock {

    public static final MapCodec<BlockTrafficLightControlBox> CODEC = simpleCodec(BlockTrafficLightControlBox::new);

    @Override
    protected MapCodec<BlockTrafficLightControlBox> codec() {
        return CODEC;
    }

    public BlockTrafficLightControlBox(BlockBehaviour.Properties properties) {
        super(properties);
        // Default state = FACING south so the creative-menu icon shows the front face (GUI rotation is [30, 225, 0], viewer sees S/W faces)
        this.registerDefaultState(this.stateDefinition.any().setValue(FACING, Direction.SOUTH));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING);
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        return this.defaultBlockState().setValue(FACING, context.getHorizontalDirection().getOpposite());
    }

    @Override
    public BlockState rotate(BlockState state, Rotation rotation) {
        return state.setValue(FACING, rotation.rotate(state.getValue(FACING)));
    }

    @Override
    public BlockState mirror(BlockState state, Mirror mirror) {
        return state.rotate(mirror.getRotation(state.getValue(FACING)));
    }
}
